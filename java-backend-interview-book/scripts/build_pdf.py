#!/usr/bin/env python3
"""Render the combined Markdown manuscript to a print-ready PDF with ReportLab.

Usage (from the repository root, with the build virtualenv active):

    python3 java-backend-interview-book/scripts/build_book.py     # refresh the combined Markdown
    python3 java-backend-interview-book/scripts/build_pdf.py      # render the PDF

Requires: reportlab (rendering) and, for the verification step, pypdf.
Bootstrap:

    python3 -m venv .venv
    .venv/bin/pip install reportlab pypdf
    .venv/bin/python java-backend-interview-book/scripts/build_pdf.py

Pandoc, LaTeX, wkhtmltopdf and WeasyPrint are not used: none of them are
available in the build environment this book was produced in, so the PDF is
generated by a self-contained ReportLab pipeline that supports the features the
book needs - title page, clickable table of contents, PDF outline bookmarks,
page numbers, tables and monospaced code blocks.

The Markdown subset understood here is exactly what the manuscript uses:
ATX headings, paragraphs, bullet lists, fenced code blocks, pipe tables,
horizontal rules, bold, italic, inline code and links.
"""
from __future__ import annotations

import html
import re
import sys
from datetime import date
from pathlib import Path

try:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER, TA_JUSTIFY
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.pdfbase import pdfmetrics
    from reportlab.platypus import (BaseDocTemplate, Frame, KeepTogether, ListFlowable,
                                    ListItem, PageBreak, PageTemplate, Paragraph,
                                    Preformatted, Spacer, Table, TableStyle)
    from reportlab.platypus.tableofcontents import TableOfContents
except ImportError:  # pragma: no cover - environment guidance
    sys.exit("reportlab is required: python3 -m venv .venv && "
             ".venv/bin/pip install reportlab pypdf")

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Java_Backend_Top_200_Interview_Questions.md"
OUTPUT = ROOT / "Java_Backend_Top_200_Interview_Questions.pdf"

TITLE = "Top 200 Java Backend Developer Interview Questions and Answers"
SUBTITLE = "For developers with 3-4 years of experience"

PAGE_W, PAGE_H = A4
MARGIN_X = 18 * mm
MARGIN_TOP = 18 * mm
MARGIN_BOTTOM = 20 * mm
FRAME_W = PAGE_W - 2 * MARGIN_X

ACCENT = colors.HexColor("#1F4E79")
ACCENT_LIGHT = colors.HexColor("#2E75B6")
CODE_BG = colors.HexColor("#F4F6F8")
CODE_BORDER = colors.HexColor("#D7DDE3")
RULE = colors.HexColor("#C9D2DA")

CODE_FONT = "Courier"
CODE_SIZE = 7.6
CODE_LEADING = 9.4


